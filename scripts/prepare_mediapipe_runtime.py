#!/usr/bin/env python3
"""Build a transparent MediaPipe runtime variant using upstream's no-op logger.

The exact Maven AAR and upstream BUILD are verified before use. Only the
TasksStatsLoggerFactory class is replaced with the factory generated by upstream
when ENABLE_TASKS_USAGE_LOGGING is not enabled. All other class/resource/native
payloads remain byte-identical. This is an openly documented build-time fork,
not a runtime reflection override or a Google security approval.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import urllib.error
import urllib.parse
import urllib.request
import zipfile

ROOT = Path(__file__).resolve().parents[1]
VERSION = "0.10.35"
DIRECTORY = ROOT / ".build-deps/mediapipe"
DEFAULT_OUTPUT = DIRECTORY / f"tasks-core-{VERSION}-no-usage-logging.aar"
MAVEN_URL = f"https://dl.google.com/dl/android/maven2/com/google/mediapipe/tasks-core/{VERSION}/tasks-core-{VERSION}.aar"
UPSTREAM_URL = f"https://raw.githubusercontent.com/google-ai-edge/mediapipe/v{VERSION}/mediapipe/tasks/java/com/google/mediapipe/tasks/core/BUILD"
ORIGINAL_BYTES = 21_342_753
ORIGINAL_SHA256 = "4edf2f33c840d682c751b3ca951b1ae0465373734776d7fb37dcef936de28ad0"
UPSTREAM_SHA256 = "bab1d480c5bc5808e1788c91e1e067120d7348137d50fe2ca764611cf5e0a6d7"
FACTORY = "com/google/mediapipe/tasks/core/logging/TasksStatsLoggerFactory.class"
FACTORY_SOURCE = ROOT / "scripts/mediapipe/TasksStatsLoggerFactory.java"
# Pinned after compiling the checked-in source with javac 17, Java 8 target,
# no debug metadata, and deterministically storing the two ZIP containers.
EXPECTED_OUTPUT_SHA256 = "25ac823c37f77d2870c32bfbe0dfae30b2b1a921b7fce395e743399c3b638bf3"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def regular_file(path: Path) -> bytes:
    if path.is_symlink() or not path.is_file():
        raise ValueError(f"Arquivo regular necessário: {path.name}")
    return path.read_bytes()


def validate_original(path: Path) -> bytes:
    data = regular_file(path)
    if len(data) != ORIGINAL_BYTES or sha256(data) != ORIGINAL_SHA256:
        raise ValueError("AAR MediaPipe original não corresponde ao tamanho/SHA-256 fixado")
    return data


def validate_upstream(path: Path) -> bytes:
    data = regular_file(path)
    if sha256(data) != UPSTREAM_SHA256:
        raise ValueError("BUILD upstream não corresponde ao SHA-256 fixado")
    return data


class HttpsOnlyRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, request, response, code, message, headers, new_url):
        if urllib.parse.urlparse(new_url).scheme != "https":
            raise ValueError("A preparação MediaPipe exige HTTPS em todo redirecionamento")
        return super().redirect_request(request, response, code, message, headers, new_url)


def atomic_install(data: bytes, path: Path) -> None:
    if path.parent.is_symlink():
        raise ValueError("Diretório de preparação não pode ser link simbólico")
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(prefix=".mediapipe-", dir=path.parent)
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as target:
            target.write(data)
            target.flush()
            os.fsync(target.fileno())
        try:
            os.link(temporary, path)
        except FileExistsError:
            if regular_file(path) != data:
                raise ValueError(f"Arquivo existente divergente preservado: {path.name}")
    finally:
        temporary.unlink(missing_ok=True)


def fetch_verified(url: str, target: Path, checksum: str, expected_bytes: int | None = None) -> bytes:
    if target.exists() or target.is_symlink():
        data = regular_file(target)
    else:
        request = urllib.request.Request(url, headers={"User-Agent": "NEXUS-MediaPipe-build/1"})
        with urllib.request.build_opener(HttpsOnlyRedirect()).open(request, timeout=120) as response:
            if urllib.parse.urlparse(response.geturl()).scheme != "https":
                raise ValueError("Download MediaPipe exige HTTPS")
            maximum = expected_bytes if expected_bytes is not None else 256 * 1024
            data = response.read(maximum + 1)
            if len(data) > maximum:
                raise ValueError("Download MediaPipe excede o tamanho permitido")
        if sha256(data) != checksum or (expected_bytes is not None and len(data) != expected_bytes):
            raise ValueError("Download MediaPipe não corresponde ao tamanho/SHA-256 fixado")
        atomic_install(data, target)
    if sha256(data) != checksum or (expected_bytes is not None and len(data) != expected_bytes):
        raise ValueError("Arquivo MediaPipe em cache divergente; ele foi preservado")
    return data


def zip_entries(data: bytes) -> dict[str, bytes]:
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        names = archive.namelist()
        if len(names) != len(set(names)):
            raise ValueError("ZIP contém entradas duplicadas")
        if any(name.startswith("/") or ".." in Path(name).parts for name in names):
            raise ValueError("ZIP contém caminho inválido")
        return {name: archive.read(name) for name in names}


def deterministic_zip(entries: dict[str, bytes]) -> bytes:
    target = io.BytesIO()
    with zipfile.ZipFile(target, "w", compression=zipfile.ZIP_STORED) as archive:
        for name, data in sorted(entries.items()):
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.create_system = 3
            info.compress_type = zipfile.ZIP_STORED
            info.external_attr = (0o40755 if name.endswith("/") else 0o100644) << 16
            archive.writestr(info, data)
    return target.getvalue()


def derive_aar(original: bytes, factory_class: bytes) -> tuple[bytes, dict]:
    if not factory_class.startswith(b"\xca\xfe\xba\xbe"):
        raise ValueError("Fábrica compilada não é uma classe Java")
    if int.from_bytes(factory_class[6:8], "big") != 52:
        raise ValueError("A fábrica precisa de bytecode Java 8 (classe 52)")
    if b"TasksStatsDummyLogger" not in factory_class or any(
        marker in factory_class for marker in (b"TasksStatsProtoLogger", b"RemoteLoggingClient", b"CCTDestination")
    ):
        raise ValueError("A fábrica precisa usar exclusivamente o logger no-op upstream")
    aar = zip_entries(original)
    classes = zip_entries(aar["classes.jar"])
    if FACTORY not in classes:
        raise ValueError("AAR original não contém a fábrica esperada")
    original_factory = classes[FACTORY]
    classes[FACTORY] = factory_class
    updated_classes = deterministic_zip(classes)
    modified_aar = {**aar, "classes.jar": updated_classes}
    output = deterministic_zip(modified_aar)
    proof = verify_derivation(original, output)
    proof["factory_original_sha256"] = sha256(original_factory)
    proof["factory_modified_sha256"] = sha256(factory_class)
    return output, proof


def verify_derivation(original: bytes, modified: bytes) -> dict:
    before = zip_entries(original)
    after = zip_entries(modified)
    if before.keys() != after.keys():
        raise ValueError("A variante alterou a lista de entradas do AAR")
    unchanged_aar = {}
    for name in before:
        if name == "classes.jar":
            continue
        if before[name] != after[name]:
            raise ValueError(f"Payload de AAR alterado indevidamente: {name}")
        unchanged_aar[name] = sha256(before[name])
    classes_before = zip_entries(before["classes.jar"])
    classes_after = zip_entries(after["classes.jar"])
    if classes_before.keys() != classes_after.keys():
        raise ValueError("A variante alterou a lista de entradas de classes.jar")
    changed = [name for name in classes_before if classes_before[name] != classes_after[name]]
    if changed != [FACTORY]:
        raise ValueError("A derivação deve alterar somente TasksStatsLoggerFactory.class")
    replacement = classes_after[FACTORY]
    if b"TasksStatsDummyLogger" not in replacement or b"TasksStatsProtoLogger" in replacement:
        raise ValueError("A variante não contém a fábrica no-op esperada")
    return {
        "only_changed_class": FACTORY,
        "unchanged_jar_entries": len(classes_before) - 1,
        "unchanged_aar_payload_sha256": dict(sorted(unchanged_aar.items())),
    }


def android_jar_from_environment() -> Path:
    sdk = os.environ.get("ANDROID_HOME") or os.environ.get("ANDROID_SDK_ROOT")
    if not sdk:
        raise ValueError("Configure ANDROID_HOME ou ANDROID_SDK_ROOT e instale platforms;android-35")
    return Path(sdk) / "platforms/android-35/android.jar"


def compile_factory(original: bytes, android_jar: Path) -> tuple[bytes, str]:
    if not android_jar.is_file() or android_jar.is_symlink():
        raise ValueError("android.jar da plataforma 35 não foi encontrado")
    java_home = os.environ.get("JAVA_HOME")
    javac = str(Path(java_home) / "bin/javac") if java_home else shutil.which("javac")
    if not javac:
        raise ValueError("Instale JDK 17 e configure JAVA_HOME para preparar MediaPipe")
    version = subprocess.run([javac, "-version"], check=True, text=True, capture_output=True).stdout.strip()
    if not re.search(r"javac 17(?:\.|$)", version):
        raise ValueError("A derivação fixada requer javac 17")
    with tempfile.TemporaryDirectory(prefix="nexus-mediapipe-javac-") as temporary_name:
        temporary = Path(temporary_name)
        jar = temporary / "original.jar"
        jar.write_bytes(zip_entries(original)["classes.jar"])
        output = temporary / "classes"
        output.mkdir()
        subprocess.run([
            javac, "-source", "8", "-target", "8", "-g:none", "-encoding", "UTF-8", "-proc:none",
            "-classpath", os.pathsep.join((str(android_jar), str(jar))), "-d", str(output), str(FACTORY_SOURCE),
        ], check=True, capture_output=True, text=True)
        return (output / FACTORY).read_bytes(), version


def prepare(output: Path = DEFAULT_OUTPUT, source_aar: Path | None = None,
            upstream_build: Path | None = None, android_jar: Path | None = None) -> dict:
    original = validate_original(source_aar) if source_aar else fetch_verified(
        MAVEN_URL, DIRECTORY / f"tasks-core-{VERSION}-original.aar", ORIGINAL_SHA256, ORIGINAL_BYTES)
    upstream = validate_upstream(upstream_build) if upstream_build else fetch_verified(
        UPSTREAM_URL, DIRECTORY / f"upstream-core-BUILD-{VERSION}", UPSTREAM_SHA256)
    # Prove the versioned source actually offers the default no-op construction;
    # never infer that an arbitrary flag can change an already compiled AAR.
    if b'ENABLE_TASKS_USAGE_LOGGING' not in upstream or b'logging/TasksStatsDummyLogger.java' not in upstream:
        raise ValueError("A fonte fixada não documenta a fábrica padrão esperada")
    factory, compiler = compile_factory(original, android_jar or android_jar_from_environment())
    derived, proof = derive_aar(original, factory)
    digest = sha256(derived)
    if digest != EXPECTED_OUTPUT_SHA256:
        raise ValueError("A derivação não corresponde ao SHA-256 reproduzível fixado")
    provenance = {
        "variant": "MediaPipe tasks-core no usage logging (NEXUS documented derivative)",
        "version": VERSION,
        "upstream_aar_url": MAVEN_URL,
        "upstream_aar_bytes": len(original),
        "upstream_aar_sha256": ORIGINAL_SHA256,
        "upstream_build_url": UPSTREAM_URL,
        "upstream_build_sha256": UPSTREAM_SHA256,
        "factory_source_sha256": sha256(regular_file(FACTORY_SOURCE)),
        "compiler": compiler,
        "class_target": "Java 8 / major 52; no debug metadata",
        "output_bytes": len(derived),
        "output_sha256": digest,
        **proof,
    }
    atomic_install(derived, output)
    # Compiler patch-version is useful evidence but does not alter output bytes.
    provenance_path = output.with_suffix(".provenance.json")
    encoded = (json.dumps(provenance, indent=2, sort_keys=True) + "\n").encode()
    if provenance_path.exists() or provenance_path.is_symlink():
        existing = json.loads(regular_file(provenance_path))
        if {k: v for k, v in existing.items() if k != "compiler"} != {k: v for k, v in provenance.items() if k != "compiler"}:
            raise ValueError("Proveniência existente divergente preservada")
    else:
        atomic_install(encoded, provenance_path)
    return provenance


def main() -> int:
    parser = argparse.ArgumentParser(description="Prepara MediaPipe verificável com logger de uso no-op upstream")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--source-aar", type=Path, help="AAR Maven local com hash exato")
    parser.add_argument("--upstream-build", type=Path, help="BUILD upstream local com hash exato")
    parser.add_argument("--android-jar", type=Path, help="android.jar da plataforma 35; padrão usa ANDROID_HOME")
    args = parser.parse_args()
    try:
        result = prepare(args.output, args.source_aar, args.upstream_build, args.android_jar)
    except (OSError, ValueError, KeyError, zipfile.BadZipFile, subprocess.CalledProcessError, urllib.error.URLError) as error:
        print(f"MediaPipe não preparado: {error}")
        return 1
    print(f"MediaPipe {VERSION} · fábrica no-op upstream · {result['output_bytes']} bytes")
    print(f"SHA-256 {result['output_sha256']}; demais payloads AAR/JAR preservados")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
